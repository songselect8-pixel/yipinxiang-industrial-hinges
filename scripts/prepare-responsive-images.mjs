import { createHash } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const projectRoot = process.cwd();
const sourceRoot = path.resolve(projectRoot, "public", "images");
const outputRoot = path.resolve(sourceRoot, "optimized");
const manifestPath = path.resolve(projectRoot, "src", "lib", "responsive-image-manifest.ts");
const requestedWidths = [64, 96, 128, 256, 384, 390, 640, 768, 1024, 1280, 1440, 1920];
const sourcePattern = /\.(?:jpe?g|png|webp)$/i;
const pipelineVersion = "responsive-webp-v1-q84-lossless-drawings";

if (!outputRoot.startsWith(`${sourceRoot}${path.sep}`)) {
  throw new Error(`Refusing to replace an image directory outside ${sourceRoot}`);
}

async function findSourceImages(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const images = [];

  for (const entry of entries) {
    if (entry.name === "optimized") continue;

    const absolutePath = path.join(directory, entry.name);
    if (entry.isDirectory()) images.push(...await findSourceImages(absolutePath));
    if (entry.isFile() && sourcePattern.test(entry.name)) images.push(absolutePath);
  }

  return images;
}

function toPublicPath(absolutePath) {
  return `/${path.relative(path.resolve(projectRoot, "public"), absolutePath).split(path.sep).join("/")}`;
}

const manifest = {};
const sourceImages = (await findSourceImages(sourceRoot)).sort();
const cacheKey = createHash("sha256");
cacheKey.update(`${pipelineVersion}:${requestedWidths.join(",")}`);
for (const sourcePath of sourceImages) {
  cacheKey.update(path.relative(sourceRoot, sourcePath));
  cacheKey.update(await fs.readFile(sourcePath));
}
const sourceKey = cacheKey.digest("hex");
const sourceKeyPath = path.resolve(projectRoot, ".image-cache-key");

try {
  const [preparedKey] = await Promise.all([
    fs.readFile(sourceKeyPath, "utf8"),
    fs.access(manifestPath),
  ]);
  if (preparedKey === sourceKey) {
    console.log(`Responsive images are current (${sourceImages.length} originals).`);
    process.exit(0);
  }
} catch {
  // A fresh checkout or changed source image needs a complete preparation pass.
}

await fs.rm(outputRoot, { recursive: true, force: true });
await fs.mkdir(outputRoot, { recursive: true });

let originalBytes = 0;
let optimizedBytes = 0;
let variantCount = 0;

for (const sourcePath of sourceImages) {
  const metadata = await sharp(sourcePath).metadata();
  if (!metadata.width) throw new Error(`Could not read image width: ${sourcePath}`);

  const sourceStat = await fs.stat(sourcePath);
  originalBytes += sourceStat.size;

  const widths = requestedWidths.filter((width) => width <= metadata.width);
  if (metadata.width < requestedWidths.at(-1) && !widths.includes(metadata.width)) widths.push(metadata.width);

  const relativePath = path.relative(sourceRoot, sourcePath);
  const parsedPath = path.parse(relativePath);
  const sourcePublicPath = toPublicPath(sourcePath);
  const variants = {};

  for (const width of widths) {
    const variantRelativePath = path.join(parsedPath.dir, `${parsedPath.name}-${width}.webp`);
    const variantPath = path.join(outputRoot, variantRelativePath);
    await fs.mkdir(path.dirname(variantPath), { recursive: true });

    const pipeline = sharp(sourcePath).rotate().resize({ width, withoutEnlargement: true });
    const isTechnicalDrawing = parsedPath.name.startsWith("drawing-");

    if (isTechnicalDrawing) {
      await pipeline.webp({ lossless: true, effort: 6 }).toFile(variantPath);
    } else {
      await pipeline.webp({ quality: 84, effort: 5, smartSubsample: true }).toFile(variantPath);
    }

    optimizedBytes += (await fs.stat(variantPath)).size;
    variantCount += 1;
    variants[width] = toPublicPath(variantPath);
  }

  manifest[sourcePublicPath] = { widths, variants };
}

const manifestSource = `// Generated by scripts/prepare-responsive-images.mjs.\n// Keep original files in public/images; page images use these responsive WebP variants.\nexport type ResponsiveImageEntry = {\n  widths: readonly number[];\n  variants: Readonly<Record<number, string>>;\n};\n\nexport const responsiveImageManifest: Readonly<Record<string, ResponsiveImageEntry>> = ${JSON.stringify(manifest, null, 2)};\n`;
await fs.writeFile(manifestPath, manifestSource, "utf8");
await fs.writeFile(sourceKeyPath, sourceKey, "utf8");

const toMegabytes = (bytes) => (bytes / 1024 / 1024).toFixed(2);
console.log(`Prepared ${variantCount} responsive WebP files from ${sourceImages.length} originals (${toMegabytes(originalBytes)} MB source; ${toMegabytes(optimizedBytes)} MB total variants).`);
